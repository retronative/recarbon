#!/usr/bin/env bash
# Regenerate the recompiler inputs for the player's default.xex and recompile.
#
#   scripts/survey.sh
#
# Runs, in the order survey/fix_switch_tables.py documents (SpeedBreaker's
# pipeline, parametrized by ReCarbon):
#   xexsurvey -> XenonAnalyse -> fix tables -> XenonRecomp (for the function
#   map) -> inline tables -> fix tables -> leaf bounds + secondary entries ->
#   XenonRecomp -> structural validation.
# Writes config/recarbon.toml (generated blocks), config/switch_tables*.toml,
# game/survey/ (image, logs) and ppc/. Needs scripts/setup_tools.sh first,
# game/files/default.xex, and Python 3.11+ (tomllib).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
PY="${PY:-$(command -v python3.15 || command -v python3.13 || command -v python3.12 || command -v python3.11 || command -v python3)}"
"$PY" -c 'import tomllib' 2>/dev/null || { echo "need Python 3.11+ (set PY=...)"; exit 1; }
XEX=game/files/default.xex
OUT=game/survey
RECOMP=(tools/XenonRecomp/build/XenonRecomp/XenonRecomp config/recarbon.toml tools/XenonRecomp/XenonUtils/ppc_context.h)
mkdir -p "$OUT"

recompile() {
  rm -rf ppc && mkdir ppc
  "${RECOMP[@]}" > "$OUT/$1" || { echo "XenonRecomp failed (see $OUT/$1)"; exit 1; }
}

# Start from scratch: drop the generated config blocks (hand-written keys and
# anything after the generated blocks, e.g. hooks, stay) and the inline tables.
"$PY" - <<'EOF'
import re
cfg = 'config/recarbon.toml'
s = open(cfg).read()
s = re.sub(r'# --- generated by survey/find_entry_points\.py --write ---\n.*?# --- end find_entry_points ---\n\n?', '', s, flags=re.S)
s = re.sub(r'\n*# --- generated by survey/leaf_switch_bounds\.py --write ---\n.*?\nfunctions = \[\n.*?\n\]\n', '\n', s, flags=re.S)
open(cfg, 'w').write(s)
EOF
echo '# Generated by survey/find_missing_tables.py' > config/switch_tables_inline.toml

tools/survey/xexsurvey "$XEX" "$OUT" > "$OUT/xexsurvey.txt"
tools/XenonRecomp/build/XenonAnalyse/XenonAnalyse "$XEX" "$OUT/switch_tables.raw.toml" > "$OUT/analyse.log"
"$PY" survey/fix_switch_tables.py
recompile recomp_pass1.log
"$PY" survey/find_missing_tables.py > config/switch_tables_inline.toml
"$PY" survey/fix_switch_tables.py
"$PY" survey/leaf_switch_bounds.py --write
"$PY" survey/find_entry_points.py --write
recompile recomp.log
"$PY" survey/validate_recomp.py "$OUT/recomp.log"
