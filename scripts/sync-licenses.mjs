#!/usr/bin/env node
// Renders ReCarbon's LICENSES/ folder and COPYING-adjacent notices as docs
// pages (docs/PLAN.md §7), so the site's license texts are ReCarbon's own.
//
//   node scripts/sync-licenses.mjs           write src/content/docs/docs/licenses/*.md
//   node scripts/sync-licenses.mjs --check   fail if they differ from the source
//
// RECARBON_SRC and the missing-source behaviour are as in gen-controls.mjs.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_SRC = '../recarbon-worker/src/cdcd3e9c533c5cad7fce2cebcadc50aab112e5c9';
// Inside the ReCarbon repository (website/), the source is the parent folder.
const IN_REPO = existsSync(resolve(ROOT, '../runtime/hid/key_map.h')) ? '..' : null;
const SRC = resolve(ROOT, process.env.RECARBON_SRC ?? IN_REPO ?? DEFAULT_SRC);
const OUT = join(ROOT, 'src/content/docs/docs/licenses');
const args = new Set(process.argv.slice(2));

function slug(file) {
	return file
		.replace(/\.(txt|md)$/, '')
		.toLowerCase()
		.replace(/[^a-z0-9.]+/g, '-')
		.replace(/\./g, '-');
}

function page(title, description, order, text) {
	// A fence longer than any run of backticks in the text keeps it verbatim.
	const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
	const fence = '`'.repeat(longest + 1);
	const front = ['---', `title: ${JSON.stringify(title)}`, `description: ${JSON.stringify(description)}`, `sidebar:`, `  order: ${order}`, '---', ''];
	return `${front.join('\n')}\n<!-- Generated by scripts/sync-licenses.mjs from ReCarbon's source. Do not edit. -->\n\n${fence}text wrap\n${text.replace(/\s+$/, '')}\n${fence}\n`;
}

function generate() {
	const files = readdirSync(join(SRC, 'LICENSES'))
		.filter((f) => /\.(txt|md)$/.test(f))
		.sort();
	const pages = new Map();
	pages.set('notice.md', page('NOTICE', "ReCarbon's copyright and license notice.", 0, readFileSync(join(SRC, 'NOTICE'), 'utf8')));
	files.forEach((f, i) => {
		const name = f.replace(/\.(txt|md)$/, '');
		const text = readFileSync(join(SRC, 'LICENSES', f), 'utf8');
		pages.set(`${slug(f)}.md`, page(name, `License text: ${name}, from ReCarbon's LICENSES folder.`, i + 1, text));
	});
	return pages;
}

function main() {
	if (!existsSync(SRC)) {
		const msg = `ReCarbon source not found at ${SRC} (set RECARBON_SRC)`;
		if (args.has('--check') && !args.has('--strict')) {
			console.warn(`sync-licenses: WARNING: ${msg}; check skipped.`);
			return 0;
		}
		console.error(`sync-licenses: ${msg}`);
		return 1;
	}
	const pages = generate();
	const existing = existsSync(OUT) ? readdirSync(OUT).filter((f) => f.endsWith('.md') && f !== 'index.md') : [];
	if (args.has('--check')) {
		const stale = existing.filter((f) => !pages.has(f));
		const changed = [...pages].filter(([f, text]) => !existsSync(join(OUT, f)) || readFileSync(join(OUT, f), 'utf8') !== text);
		for (const f of [...stale, ...changed.map(([f]) => f)]) console.error(`sync-licenses: licenses/${f} is out of date. Run: npm run sync:licenses`);
		if (stale.length || changed.length) return 1;
		console.log(`sync-licenses: ${pages.size} pages in sync`);
		return 0;
	}
	mkdirSync(OUT, { recursive: true });
	for (const f of existing) if (!pages.has(f)) rmSync(join(OUT, f));
	for (const [f, text] of pages) writeFileSync(join(OUT, f), text);
	console.log(`sync-licenses: wrote ${pages.size} pages`);
	return 0;
}

process.exit(main());
